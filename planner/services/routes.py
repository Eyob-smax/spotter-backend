"""Find exactly three distinct truck routes (when the road network allows it).

TomTom often returns fewer alternatives than requested on long trips (verified:
NYC→Chicago returns 2 of 4 requested). Missing routes are generated by forcing
the trip through a waypoint offset sideways from the fastest route, and are
labelled ``source="tomtom_via"`` so the UI can say so.
"""

from __future__ import annotations

import logging
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from datetime import datetime
from string import ascii_uppercase

from planner.domain.geo import LatLon, Polyline, destination_point, haversine_m, route_similarity, simplify_to_budget
from planner.exceptions import PlannerError

from .tomtom import ParsedRoute, TomTomClient

logger = logging.getLogger(__name__)

TARGET_ROUTES = 3
PRIMARY_ALTERNATIVES = 2  # 4 alternatives cost ~21 s on cross-country trips vs ~12 s for 2
DUPLICATE_SIMILARITY = 0.9
DETOUR_MAX_DURATION_RATIO = 1.6
# (fraction along the fastest route, side): +1 = right of travel direction, -1 = left.
DETOUR_CANDIDATES = ((0.5, 1), (0.5, -1), (0.33, 1), (0.67, -1), (0.33, -1), (0.67, 1))
DETOUR_PARALLELISM = 2
SIMILARITY_SAMPLE_M = 1_000
GEOMETRY_POINT_BUDGET = 1_500
NAME_MIN_SHARE = 0.05  # a road must carry >= 5% of a route to name it


@dataclass(frozen=True)
class PlannedRoute:
    id: str
    name: str
    source: str  # "tomtom" | "tomtom_via"
    parsed: ParsedRoute
    line: Polyline  # simplified geometry with aligned cumulative distance/time


@dataclass
class _Candidate:
    parsed: ParsedRoute
    source: str
    samples: list[LatLon]


def detour_offset_m(origin: LatLon, destination: LatLon) -> float:
    return min(max(0.2 * haversine_m(origin, destination), 15_000.0), 120_000.0)


def detour_waypoint(route: Polyline, fraction: float, side: int, offset_m: float) -> LatLon:
    distance = route.length_m * fraction
    point, _ = route.at_distance(distance)
    heading = route.bearing_at_distance(distance, lookahead_m=5_000)
    return destination_point(point, heading + 90 * side, offset_m)


def _is_distinct(candidate: _Candidate, kept: list[_Candidate]) -> bool:
    return all(route_similarity(candidate.samples, k.samples) < DUPLICATE_SIMILARITY for k in kept)


def _candidate(parsed: ParsedRoute, source: str) -> _Candidate:
    return _Candidate(parsed=parsed, source=source, samples=parsed.line.resample(SIMILARITY_SAMPLE_M))


def _name_routes(routes: list[_Candidate]) -> list[str]:
    def significant(c: _Candidate) -> list[str]:
        limit = NAME_MIN_SHARE * c.parsed.distance_m
        return [r for r in c.parsed.main_roads if c.parsed.road_distances[r] >= limit]

    roads = [significant(c) for c in routes]
    base = [f"via {r[0]}" if r else "" for r in roads]
    names = list(base)
    for i, name in enumerate(base):
        if not name or base.count(name) == 1:
            continue
        # Same main road as another route: add this route's most-driven road the others don't use.
        others = {road for j, rs in enumerate(roads) if j != i and base[j] == name for road in rs}
        distinct = next((road for road in roads[i][1:] if road not in others), None)
        if distinct:
            names[i] = f"{name} · {distinct}"
    final = []
    for i, name in enumerate(names):
        duplicate = name and sum(1 for n in names if n == name) > 1
        final.append(name if name and not duplicate else f"Route {ascii_uppercase[i]}")
    return final


def find_routes(
    client: TomTomClient,
    origin: LatLon,
    destination: LatLon,
    *,
    load_lb: float,
    depart_at: datetime,
) -> tuple[list[PlannedRoute], list[str]]:
    primary = client.calculate_routes(
        [origin, destination], load_lb=load_lb, depart_at=depart_at, max_alternatives=PRIMARY_ALTERNATIVES
    )
    kept: list[_Candidate] = []
    for parsed in primary:
        cand = _candidate(parsed, "tomtom")
        if _is_distinct(cand, kept):
            kept.append(cand)
    provider_count = len(kept)

    if len(kept) < TARGET_ROUTES:
        kept.extend(_find_detours(client, origin, destination, kept, load_lb=load_lb, depart_at=depart_at))

    kept.sort(key=lambda c: c.parsed.duration_s)
    kept = kept[:TARGET_ROUTES]
    names = _name_routes(kept)

    planned = []
    for i, (cand, name) in enumerate(zip(kept, names)):
        keep_idx = simplify_to_budget(cand.parsed.line.points, GEOMETRY_POINT_BUDGET)
        planned.append(
            PlannedRoute(
                id=ascii_uppercase[i],
                name=name,
                source=cand.source,
                parsed=cand.parsed,
                line=cand.parsed.line.subset(keep_idx),
            )
        )

    notices: list[str] = []
    detour_ids = [r.id for r in planned if r.source == "tomtom_via"]
    if detour_ids:
        listed = " and ".join(f"Route {i}" for i in detour_ids)
        notices.append(
            f"The routing service returned {provider_count} distinct "
            f"route{'s' if provider_count != 1 else ''}; {listed} "
            f"{'was' if len(detour_ids) == 1 else 'were'} generated through a detour waypoint."
        )
    if len(planned) < TARGET_ROUTES:
        notices.append(f"Only {len(planned)} distinct truck route{'s' if len(planned) != 1 else ''} could be found.")
    return planned, notices


def _find_detours(
    client: TomTomClient,
    origin: LatLon,
    destination: LatLon,
    kept: list[_Candidate],
    *,
    load_lb: float,
    depart_at: datetime,
) -> list[_Candidate]:
    fastest = min(kept, key=lambda c: c.parsed.duration_s)
    offset = detour_offset_m(origin, destination)
    max_duration = fastest.parsed.duration_s * DETOUR_MAX_DURATION_RATIO
    found: list[_Candidate] = []

    def attempt(spec: tuple[float, int]) -> ParsedRoute | None:
        via = detour_waypoint(fastest.parsed.line, spec[0], spec[1], offset)
        try:
            routes = client.calculate_routes(
                [origin, via, destination], load_lb=load_lb, depart_at=depart_at, max_alternatives=0
            )
        except PlannerError as exc:
            logger.info("Detour candidate %s rejected: %s", spec, exc.code)
            return None
        return routes[0] if routes else None

    specs = list(DETOUR_CANDIDATES)
    with ThreadPoolExecutor(max_workers=DETOUR_PARALLELISM) as pool:
        while specs and len(kept) + len(found) < TARGET_ROUTES:
            batch, specs = specs[:DETOUR_PARALLELISM], specs[DETOUR_PARALLELISM:]
            for parsed in pool.map(attempt, batch):
                if parsed is None or len(kept) + len(found) >= TARGET_ROUTES:
                    continue
                if parsed.duration_s > max_duration:
                    continue
                cand = _candidate(parsed, "tomtom_via")
                if _is_distinct(cand, kept + found):
                    found.append(cand)
    return found
